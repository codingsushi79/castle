// Copies Castle's puzzle set into the server, so the server picks rush and
// battle puzzles and checks every move without the app ever holding a solution.
// Run after the app's public/data/puzzles.tsv changes: npm run sync-puzzles
import fs from "node:fs";
const src = new URL("../../public/data/puzzles.tsv", import.meta.url);
const rows = fs.readFileSync(src, "utf8").split("\n").map((l) => l.split("\t")).filter((c) => c.length >= 4);
const compact = rows.map(([id, fen, moves, rating]) => [id, fen, moves, Number(rating) || 1500].join("\t")).join("\n");
fs.writeFileSync(new URL("../lib/puzzles-data.ts", import.meta.url),
  `// Generated by scripts/sync-puzzles.mjs from the app's puzzle set. Do not edit.\nexport const PUZZLES_TSV = ${JSON.stringify(compact)};\n`);
console.log(`${rows.length} puzzles written.`);
